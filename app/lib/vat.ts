/**
 * 부가세 포함 금액 (2026-10-09 (금) 대표 결정 · 금액에 부가세를 더해 표기)
 *
 * 화면에 적는 금액은 전부 부가세 포함이다. 받는 돈은 그대로이고 표기만 바뀐다.
 * 공급가를 원본으로 두고 이 함수를 거쳐 화면 금액을 만든다 — 공급가를 고치면 화면 금액이 따라간다.
 * 정수 연산으로 계산해 소수 오차가 생기지 않게 한다 (330,000 × 1.1 = 363,000.00000000006 같은 값).
 */
export function withVat(supply: number): number {
  return Math.round((supply * 11) / 10);
}
